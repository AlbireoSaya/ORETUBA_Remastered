# 需要「归一化」而非「单次替换」的规则（替换结果本身也匹配模式，用正则一次到位、可反复安全执行）
# 结构：`(日文原文必须包含的片段, 编译好的正则, 替换串)`
REGEX_RULES = [
    # ポッポ → 小咕咕：把 2 个及以上的「小」前缀归一为一个（要求 ≥2 才匹配，保证幂等）
    ('ポッポ', re.compile(r'小{2,}咕咕'), '小咕咕'),
    # ファーック → 拖音感叹词，按硬约束「感叹词拖音一律 ～」归一（含历史上叠出的多个破折号）
    ('ファーック', re.compile(r'操—+'), '操～'),
    ('ファック', re.compile(r'操—+'), '操～'),
    # ハヤブサ → 游隼 / マーガリン → 人造黄油：同属「替换串包含被替换串」的叠字污染，一并归一
    ('ハヤブサ', re.compile(r'游{2,}隼'), '游隼'),
    ('マーガリン', re.compile(r'(?:人造){2,}黄油'), '人造黄油'),
]


def load_batch(name):
    rows = {}
    with open(os.path.join(BATCH, name + '.tsv'), encoding='utf-8') as f:
        f.readline()
        for line in f:
            p = line.rstrip('\n').split('\t')
            if len(p) >= 7:
                rows[p[1]] = p[6].replace('\\n', '\n')
    return rows


def main():
    grand = 0
    # 幂等守卫：替换串若包含被替换串（如 old='咕咕' / new='小咕咕'），每跑一轮就会再叠一次，
    # 必须拒绝执行——这类归一化一律改由 REGEX_RULES 处理。
    safe, bad = [], []
    for r in RULES:
        (bad if r[1] in r[2] else safe).append(r)
    for need, old, new in bad:
        print('⚠️ 跳过非幂等规则（old 包含于 new）：%s → %s（need=%s）' % (old, new, need))
    names = sys.argv[1:]
    if not names:   # 缺省=全部已产出译文
        names = sorted(os.path.basename(p)[:-4]
                       for p in glob.glob(os.path.join(TRANS, 'batch_*.tsv')))
    for name in names:
        src = load_batch(name)
        p = os.path.join(TRANS, name + '.tsv')
        if not os.path.exists(p):
            print('%s: 无译文，跳过' % name)
            continue
        out, n = [], 0
        for line in open(p, encoding='utf-8'):
            line = line.rstrip('\n')
            if not line.strip():
                continue
            slot = line.split('\t')[0]
            cn = '\t'.join(line.split('\t')[1:])
            jb = src.get(slot, '')
            for need, old, new in safe:
                if need in jb and old in cn and old != new:
                    k = cn.count(old)
                    cn = cn.replace(old, new)
                    n += k
            for need, pat, new in REGEX_RULES:
                if need in jb:
                    cn, k = pat.subn(new, cn)
                    n += k
            out.append(slot + '\t' + cn)
        open(p, 'w', encoding='utf-8', newline='').write('\n'.join(out) + '\n')
        if n:
            print('%s: 回改 %d 处' % (name, n))
        grand += n
    print('合计 %d 处' % grand)


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    main()
