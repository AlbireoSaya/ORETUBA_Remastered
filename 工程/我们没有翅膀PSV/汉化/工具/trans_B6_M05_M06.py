FILES = [
    ("M05_01", M05_01, 164),
    ("M05_02", M05_02, 156),
    ("M06_01", M06_01, 56),
    ("M06_02", M06_02, 154),
    ("M06_03", M06_03, 243),
]


def main():
    report = []
    for name, table, expect in FILES:
        sp = os.path.join(SRC, name + ".tsv")
        with open(sp, encoding="utf-8-sig") as f:
            raw = f.read()
        assert "\r" not in raw, "%s 含 CR，需先确认换行口径" % name
        rows = [r for r in raw.split("\n") if r != ""]
        body = rows[1:]
        assert len(body) == expect, "%s 原文行数 %d != %d" % (name, len(body), expect)
        keys = set()
        for r in body:
            keys.add(int(r.split("\t")[0]))
        missing = sorted(set(range(1, expect + 1)) - set(table))
        extra = sorted(set(table) - keys)
        assert not missing, "%s 缺译行: %s" % (name, missing)
        assert not extra, "%s 多余键: %s" % (name, extra)
        out = [rows[0] + "\t中文"]
        for r in body:
            idx = int(r.split("\t")[0])
            out.append(r + "\t" + table[idx].replace("\u3000", ""))
        # 自检：无全角空格、无半角标点、引号已转
        bad = []
        for r in body:
            idx = int(r.split("\t")[0])
            t = table[idx].replace("\u3000", "")
            for ch in t:
                if ch in ',.;:!?()':
                    bad.append((idx, "半角标点 " + ch))
                    break
                if ch in "\u300c\u300d\u300e\u300f\u301c\u2500":
                    bad.append((idx, "未转符号 " + ch))
                    break
        if bad:
            raise SystemExit("%s 自检失败: %s" % (name, bad[:10]))
        # \n 保底：条数一致
        for r in body:
            idx = int(r.split("\t")[0])
            src_cells = r.split("\t")
            ja = src_cells[6]
            zh = table[idx].replace("\u3000", "")
            if ja.count("\\n") != zh.count("\\n"):
                raise SystemExit("%s 行%d 换行数不符: src=%d dst=%d"
                                 % (name, idx, ja.count("\\n"), zh.count("\\n")))
        dp = os.path.join(DST, name + ".tsv")
        with open(dp, "w", encoding="utf-8-sig", newline="") as f:
            f.write("\n".join(out) + "\n")
        report.append((name, len(body), len(out) - 1))
    for n, a, b in report:
        print("%s 输入 %d 行 / 输出 %d 行 %s" % (n, a, b, "OK" if a == b else "MISMATCH"))


if __name__ == "__main__":
    main()
