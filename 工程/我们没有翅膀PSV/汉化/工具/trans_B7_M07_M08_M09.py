def main():
    files = ['M09_02', 'M07_02', 'M07_01', 'M08_01']
    for name in files:
        src = os.path.join(BASE, '原文', name + '.tsv')
        dst = os.path.join(BASE, '译文', name + '.tsv')
        with io.open(src, encoding='utf-8-sig', newline='') as f:
            raw = f.read()
        eol = '\r\n' if '\r\n' in raw else '\n'
        rows = raw.split(eol)
        while rows and rows[-1] == '':
            rows.pop()
        head = rows[0].split('\t')
        assert len(head) == 7, (name, head)
        body = rows[1:]
        cn = CN[name]
        assert len(cn) == len(body), (name, len(cn), len(body))
        out = ['\t'.join(head + ['中文'])]
        for i, line in enumerate(body):
            cols = line.split('\t')
            assert len(cols) == 7, (name, i + 1, len(cols), line[:40])
            text = cn[i].replace('@@', chr(92) + 'n')
            out.append('\t'.join(cols + [text]))
        with io.open(dst, 'w', encoding='utf-8-sig', newline='') as f:
            f.write(eol.join(out) + eol)
        print(name, 'rows:', len(body), '-> written', len(out) - 1, '| eol:', repr(eol))


if __name__ == '__main__':
    main()
