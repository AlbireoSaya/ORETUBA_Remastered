def rows_for(term, spec, data):
    t = data["terms"][term]
    old = t["old_by_corpus"]
    jp = t["jp_by_corpus"]
    out = []
    if old:
        # 按源聚合
        per = {}
        for key, n in old.items():
            src, stream = key.split("/", 1)
            per.setdefault(src, []).append((stream, n))
        for src, lst in sorted(per.items()):
            tot = sum(n for _, n in lst)
            detail = "＋".join(f"{STREAM.get(s, s)}{n}" for s, n in sorted(lst))
            jpt = sum(n for k, n in jp.items() if k.startswith(src + "/"))
            out.append({
                "jp": term, "old": spec["old_disp"], "new": t["new"], "cat": t["cat"],
                "scope": SRCNAME[src], "cnt": tot,
                "evid": EVID.get(term, ""),
                "note": f"日文原词槽 {jpt}；旧写法分布：{detail}；语料文件：{CORPUSFILE[src]}",
            })
    else:
        jpt = t["jp_total_slots"]
        out.append({
            "jp": term, "old": spec["old_disp"], "new": t["new"], "cat": t["cat"],
            "scope": "全部（无旧写法残留）", "cnt": 0,
            "evid": EVID.get(term, ""),
            "note": f"日文原词槽 {jpt}；源语料中未检出旧写法（R 已于 2026-09-15 通篇替换）",
        })
    return out


