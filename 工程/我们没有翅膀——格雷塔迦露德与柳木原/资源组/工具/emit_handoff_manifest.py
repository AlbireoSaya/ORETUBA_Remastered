def measure(rel: str, prefer_data_root: bool = False) -> str:
    """实测规模：目录 -> '<n> 文件 / <bytes> B'；文件 -> '<lines> 行 / <bytes> B'。"""
    p = resolve(rel, prefer_data_root)
    if os.path.isdir(p):
        n = 0
        b = 0
        for root, _d, files in os.walk(p):
            for f in files:
                fp = os.path.join(root, f)
                try:
                    b += os.path.getsize(fp)
                    n += 1
                except OSError:
                    pass
        return f"{n} 文件 / {b:,} B ({b/1024/1024:,.1f} MiB)"
    # 通配路径（形如 a\{x,y}\）单独处理
    if "{" in rel:
        return _measure_glob(rel, prefer_data_root)
    if not os.path.isfile(p):
        return "未核实（路径不存在）"
    b = os.path.getsize(p)
    lines = 0
    try:
        with open(p, "rb") as f:
            for _ in f:
                lines += 1
    except OSError:
        pass
    return f"{lines:,} 行 / {b:,} B ({b/1024/1024:,.2f} MiB)"


def _expand_braces(rel: str) -> list[str]:
    i = rel.index("{")
    j = rel.index("}", i)
    pre, post = rel[:i], rel[j + 1:]
    out = []
    for part in rel[i + 1:j].split(","):
        out.append(pre + part + post)
    return out


def _measure_glob(rel: str, prefer_data_root: bool = False) -> str:
    paths = _expand_braces(rel)
    nfiles = 0
    b = 0
    lines = 0
    missing = 0
    for q in paths:
        p = resolve(q, prefer_data_root)
        if os.path.isdir(p):
            for root, _d, files in os.walk(p):
                for f in files:
                    fp = os.path.join(root, f)
                    try:
                        b += os.path.getsize(fp)
                        nfiles += 1
                    except OSError:
                        pass
        elif os.path.isfile(p):
            nfiles += 1
            b += os.path.getsize(p)
            with open(p, "rb") as f:
                for _ in f:
                    lines += 1
        else:
            missing += 1
    note = f"；{missing} 项路径未命中" if missing else ""
    return f"{len(paths)} 项 / {nfiles} 文件 / {lines:,} 行 / {b:,} B ({b/1024/1024:,.2f} MiB){note}"


def main() -> int:
    os.makedirs(OUT_DIR, exist_ok=True)
    rows = []
    for item in ITEMS:
        name, rel, typ, tracked, consumer, note = item[:6]
        prefer = item[6] if len(item) > 6 else False
        size = measure(rel, prefer)
        rows.append((name, rel, typ, size, tracked, consumer, note))
        print(f"[{name}] {size}")
    header = ["产物", "路径", "类型", "规模（实测）", "是否入库", "消费方", "备注"]
    with open(OUT_TSV, "w", encoding="utf-8", newline="\n") as f:
        f.write("\t".join(header) + "\n")
        for r in rows:
            f.write("\t".join(c.replace("\t", " ") for c in r) + "\n")
    print(f"\n写出 {OUT_TSV}（{len(rows)} 项）")
    return 0


