def spk_table():
    rows = []
    for jp, (cn, src, note) in sorted(SPK.items(), key=lambda kv: -int(0) if False else 0):
        rows.append('| %s | **%s** | %s | %s |' % (jp, cn, note or '—', src))
    return '\n'.join(rows)


